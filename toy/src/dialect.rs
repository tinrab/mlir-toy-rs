//! The Toy dialect (chapter 2).
//!
//! MLIR is designed to be extended with *dialects*: groups of operations, types, and attributes under a unique namespace.
//! The Toy dialect captures the semantics of the language: tensor operations such as `toy.transpose` and `toy.mul`, generic (unshaped) tensors, and later structs.
//! Keeping these high-level semantics in the IR allows language-specific analyses and optimizations before lowering to lower-level dialects.
//!
//! The C++ tutorial defines the dialect statically with ODS (`Ops.td`) and `TableGen`.
//! We define it at runtime instead:
//!
//! 1. The structure of the operations and types is written in IRDL (see `toy.irdl.mlir`) and loaded into the context with `mlirLoadIRDLDialects`.
//! 2. The behavior ODS adds through traits and C++ hooks is attached to the loaded operations from Rust: the `Terminator` trait of `toy.return`, `Pure` (no side effects), and custom verifiers.
//!
//! Typed Rust wrappers, such as [`AddOp`], replace the C++ classes generated by ODS.
//!
//! One difference shows in the printed IR: a dynamic dialect cannot define a custom assembly format, so Toy operations print in MLIR's *generic* form, which spells out every operand, attribute, and type:
//!
//! ```mlir
//! %0 = "toy.transpose"(%arg0) : (tensor<*xf64>) -> tensor<*xf64>
//! ```
//!
//! instead of the tutorial's `%0 = toy.transpose(%arg0 : tensor<*xf64>) to tensor<*xf64>`.
//! Both forms describe exactly the same IR.

